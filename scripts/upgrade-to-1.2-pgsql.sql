-- Events times; none for all day events
ALTER TABLE galette_events_events
  ADD COLUMN begin_time time default NULL,
  ADD COLUMN end_time time default NULL;

-- Identifiers are identity columns, as in Galette core; their sequence goes on from the current identifiers
ALTER TABLE galette_events_events ALTER COLUMN id_event DROP DEFAULT;
DROP SEQUENCE IF EXISTS galette_events_events_id_seq;
ALTER TABLE galette_events_events ALTER COLUMN id_event ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('galette_events_events', 'id_event'), COALESCE(MAX(id_event), 0) + 1, false) FROM galette_events_events;

ALTER TABLE galette_events_bookings ALTER COLUMN id_booking DROP DEFAULT;
DROP SEQUENCE IF EXISTS galette_events_bookings_id_seq;
ALTER TABLE galette_events_bookings ALTER COLUMN id_booking ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('galette_events_bookings', 'id_booking'), COALESCE(MAX(id_booking), 0) + 1, false) FROM galette_events_bookings;

ALTER TABLE galette_events_activities ALTER COLUMN id_activity DROP DEFAULT;
DROP SEQUENCE IF EXISTS galette_events_activities_id_seq;
ALTER TABLE galette_events_activities ALTER COLUMN id_activity ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('galette_events_activities', 'id_activity'), COALESCE(MAX(id_activity), 0) + 1, false) FROM galette_events_activities;

ALTER TABLE galette_events_activitiesbookings ALTER COLUMN id_activitybooking DROP DEFAULT;
DROP SEQUENCE IF EXISTS galette_events_activitiesbookings_id_seq;
ALTER TABLE galette_events_activitiesbookings ALTER COLUMN id_activitybooking ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('galette_events_activitiesbookings', 'id_activitybooking'), COALESCE(MAX(id_activitybooking), 0) + 1, false) FROM galette_events_activitiesbookings;

-- Dates without default values, payment method is a payment type identifier
ALTER TABLE galette_events_events
  ALTER COLUMN begin_date DROP DEFAULT,
  ALTER COLUMN end_date DROP DEFAULT,
  ALTER COLUMN creation_date DROP DEFAULT;
ALTER TABLE galette_events_bookings
  ALTER COLUMN booking_date DROP DEFAULT,
  ALTER COLUMN creation_date DROP DEFAULT;
ALTER TABLE galette_events_activities
  ALTER COLUMN creation_date DROP DEFAULT;
ALTER TABLE galette_events_bookings
  ALTER COLUMN payment_method DROP DEFAULT,
  ALTER COLUMN payment_method TYPE integer;

-- Events published on public pages
ALTER TABLE galette_events_events
  ADD COLUMN is_public boolean default FALSE NOT NULL;

-- Short presentation of events, for lists
ALTER TABLE galette_events_events
  ADD COLUMN summary character varying(255) default NULL;

-- Personal calendar subscriptions
CREATE TABLE galette_events_feeds (
  id_adh integer NOT NULL REFERENCES galette_adherents (id_adh) ON DELETE CASCADE ON UPDATE CASCADE,
  token character(64) NOT NULL,
  creation_date timestamp NOT NULL,
  PRIMARY KEY (id_adh),
  UNIQUE (token)
);
